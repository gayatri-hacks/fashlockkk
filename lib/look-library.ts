const scoreLook = (look: LookLibraryItem, signals: string[]) => {
  const searchable = [
    look.title,
    look.gender,
    look.trendCluster,
    look.category,
    look.aesthetic,
    look.occasion,
    look.season,
    look.feeling,
    look.whyNow,
    ...look.pieces,
    ...look.colours,
    ...look.materials,
    ...look.tags,
    ...look.shopTerms,
  ]
    .join(" ")
    .toLowerCase();

  return signals.reduce((score, signal) => {
    const normalized = signal.toLowerCase().trim();
    if (!normalized) return score;
    return searchable.includes(normalized) ? score + 2 : score;
  }, 0);
};

