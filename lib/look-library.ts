const scoreStyleIdea = (idea: StyleIdea, signals: string[], savedLookIds?: Set<string>) => {
  const searchable = [
    idea.title,
    idea.description,
    idea.category,
    idea.season,
    idea.gender,
    ...idea.mood,
    ...idea.aesthetic,
    ...idea.references,
    ...idea.trendDrivers,
    ...idea.sourceSignals,
    ...idea.variations.flatMap((variation) => [
      variation.title,
      variation.occasion,
      variation.stylingNote,
      variation.whyItWorks,
      ...variation.pieces,
      ...variation.tags,
      ...variation.colours,
      ...variation.materials,
      ...variation.shopTerms,
    ]),
  ]
    .join(" ")
    .toLowerCase();

  const signalScore = signals.reduce((score, signal) => {
    const normalized = signal.toLowerCase().trim();
    if (!normalized) return score;
    return searchable.includes(normalized) ? score + 2 : score;
  }, 0);
  const saveScore = savedLookIds && idea.variations.some((variation) => savedLookIds.has(variation.id)) ? 5 : 0;
  return signalScore + saveScore;
};

export const rankStyleIdeas = ({
  trendDrivers = [],
  profileSignals = [],
  savedLookIds,
  gender,
}: {
  trendDrivers?: string[];
  profileSignals?: string[];
  savedLookIds?: Set<string>;
  gender?: "female" | "male";
} = {}) => {
  const signals = [...trendDrivers, ...profileSignals];
  return styleIdeas
    .filter((idea) => (gender ? idea.gender === gender : true))
    .map((idea, index) => ({ idea, index, score: scoreStyleIdea(idea, signals, savedLookIds) }))
    .sort((a, b) => b.score - a.score || a.index - b.index)
    .map(({ idea }) => idea);
};

export function buildShopTermsForVariation(variation: LookVariation) {
  const mappedTerms = variation.shoppingMap
    ? Object.values(variation.shoppingMap).flatMap((terms) => terms || [])
    : [];
  return unique([...variation.shopTerms, ...mappedTerms]).slice(0, 6);
}

