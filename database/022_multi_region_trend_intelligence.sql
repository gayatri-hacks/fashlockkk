    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'regional_trend_scores' and policyname = 'regional trend scores are readable'
  ) then
    create policy "regional trend scores are readable"
      on regional_trend_scores for select
      using (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'global_trend_scores' and policyname = 'global trend scores are readable'
  ) then
    create policy "global trend scores are readable"
      on global_trend_scores for select
      using (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'trend_editorial_names' and policyname = 'trend editorial names are readable'
  ) then
    create policy "trend editorial names are readable"
      on trend_editorial_names for select
      using (true);
  end if;
end $$;
